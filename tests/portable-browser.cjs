// Local fixture only. Run with NODE_PATH pointing at a Playwright installation.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
    const url = process.env.PORTABLE_TEST_URL || 'http://127.0.0.1:8765/extras/portable-os/';
    if (!['127.0.0.1', 'localhost'].includes(new URL(url).hostname)) throw new Error('Browser mutations are restricted to the local simulated fixture.');
    const options = {headless: true};
    if (process.platform === 'win32') options.channel = 'msedge';
    const browser = await chromium.launch(options);
    try {
        const page = await browser.newPage({viewport: {width: 1440, height: 1060}});
        assert.equal((await page.request.post(new URL('/__test/reset', url).href, {headers: {'X-Portable-Test': '1'}})).status(), 200);
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(url);
        await page.locator('#test-alert').waitFor({state: 'visible'});
        await page.getByRole('heading', {name: 'Vue d’ensemble', exact: true}).waitFor();
        assert.equal(await page.locator('.metric').count(), 4);
        const output = path.resolve('private'); fs.mkdirSync(output, {recursive: true});
        await page.screenshot({path: path.join(output, 'portable-os-desktop.png'), fullPage: true, animations: 'disabled'});
        const idle = () => page.waitForFunction(() => document.body.getAttribute('aria-busy') === 'false');
        const navigate = async id => { await idle(); await page.locator(`[data-route="${id}"]`).click(); await idle(); };
        await navigate('share');
        await page.getByRole('button', {name: 'Gestion Web', exact: true}).click();
        const modal = page.getByRole('dialog');
        await modal.getByRole('button', {name: 'Monter pour le Web'}).click();
        assert.equal(await modal.isVisible(), true, 'Ejection checkbox must be required');
        await modal.getByRole('checkbox').check();
        await modal.getByRole('button', {name: 'Monter pour le Web'}).click();
        await page.getByRole('cell', {name: 'welcome.txt', exact: true}).waitFor();
        await idle();
        await page.getByRole('button', {name: 'Fichier vide', exact: true}).click();
        await modal.getByRole('textbox').fill('rapport.txt');
        await modal.getByRole('button', {name: 'Confirmer', exact: true}).click();
        await page.getByRole('cell', {name: 'rapport.txt', exact: true}).waitFor();
        await idle();
        await page.locator('#view input[type=file]').setInputFiles({name: 'import.txt', mimeType: 'text/plain', buffer: Buffer.from('test upload')});
        await page.getByRole('cell', {name: 'import.txt', exact: true}).waitFor();
        await idle();
        await page.getByRole('button', {name: 'Renommer rapport.txt', exact: true}).click();
        await modal.getByRole('textbox').fill('rapport-final.txt');
        await modal.getByRole('button', {name: 'Confirmer', exact: true}).click();
        await page.getByRole('cell', {name: 'rapport-final.txt', exact: true}).waitFor();
        await idle();
        await page.getByRole('button', {name: 'Supprimer rapport-final.txt', exact: true}).click();
        await modal.getByRole('button', {name: 'Supprimer', exact: true}).click();
        await page.getByRole('cell', {name: 'rapport-final.txt', exact: true}).waitFor({state: 'detached'});
        await navigate('kvm');
        const frame = page.locator('iframe[src="/kvm/"]');
        await frame.waitFor(); await frame.evaluate(node => { node.dataset.persistence = 'retained'; });
        const native = page.frameLocator('iframe[src="/kvm/"]');
        await page.getByRole('button', {name: 'Activer clavier / souris'}).click();
        await native.locator('#stream-window').press('a');
        await native.locator('#stream-window').click();
        await native.locator('#shortcut').click();
        await native.locator('#macro').click();
        await native.getByLabel('Qualité native').selectOption('60');
        assert.ok(await frame.evaluate(node => node.contentWindow.lifecycle.down > 0));
        assert.ok(await frame.evaluate(node => node.contentWindow.lifecycle.up > 0));
        assert.ok(await frame.evaluate(node => node.contentWindow.lifecycle.mouse > 0));
        assert.equal(await frame.evaluate(node => node.contentWindow.lifecycle.shortcuts), 1);
        assert.equal(await frame.evaluate(node => node.contentWindow.lifecycle.macros), 1);
        await page.getByRole('button', {name: 'Plein écran', exact: true}).click();
        await page.waitForFunction(() => !!document.fullscreenElement);
        await page.evaluate(() => document.exitFullscreen());
        const releases = await frame.evaluate(node => node.contentWindow.lifecycle.releases);
        await navigate('images');
        assert.ok(await frame.evaluate((node, previous) => node.contentWindow.lifecycle.releases > previous, releases));
        await page.getByRole('cell', {name: 'rescue.iso', exact: true}).waitFor();
        await navigate('kvm');
        assert.equal(await frame.getAttribute('data-persistence'), 'retained');
        await native.getByRole('link', {name: 'Images natives', exact: true}).click();
        await page.getByRole('heading', {name: 'Images & Drive 0', exact: true}).waitFor();
        assert.equal(await frame.evaluate(node => node.contentWindow.unexpectedNativeNavigation), undefined);
        await navigate('terminal');
        await page.locator('iframe[src="/extras/webterm/ttyd/"]').waitFor();
        await navigate('network');
        await page.getByRole('heading', {name: 'Réseaux enregistrés'}).waitFor();
        await page.getByRole('cell', {name: 'Atelier', exact: true}).waitFor();
        await navigate('tools');
        await page.getByRole('button', {name: 'Lire les journaux'}).click();
        await page.getByText('Local fixture: no remote journal accessed.').waitFor();
        await navigate('settings');
        await page.getByLabel('Thème').selectOption('light');
        assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
        await page.getByLabel('Thème').selectOption('dark');
        await navigate('share');
        await page.getByRole('button', {name: 'Connecter en USB', exact: true}).click();
        await modal.getByRole('button', {name: 'Connecter', exact: true}).click(); await idle();
        await page.getByRole('button', {name: 'Gestion Web', exact: true}).click();
        await modal.getByRole('checkbox').check();
        await modal.getByRole('button', {name: 'Monter pour le Web'}).click();
        await page.getByText('Éjection PC requise (simulation).', {exact: true}).waitFor();
        await navigate('dashboard');
        await page.setViewportSize({width: 390, height: 844});
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'No mobile page overflow');
        // Keep error feedback tested above, then capture the stable responsive UI.
        await page.locator('.toast').evaluateAll(nodes => nodes.forEach(node => node.remove()));
        await page.screenshot({path: path.join(output, 'portable-os-mobile.png'), fullPage: true, animations: 'disabled'});
        await page.getByRole('button', {name: 'Ouvrir la navigation'}).click();
        await page.locator('[data-route="power"]').click();
        await page.getByRole('heading', {name: 'Batterie & alimentation', exact: true}).waitFor();
        assert.equal(await page.evaluate(() => document.body.classList.contains('nav-open')), false);
        assert.equal(await page.evaluate(() => performance.getEntriesByType('navigation').length), 1);
        assert.deepEqual(errors, []);
        process.stdout.write('Browser integration passed: dashboard, SHARE CRUD/upload/ejection guard, persistent KVM, images, network, logs, themes, mobile navigation.\n');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
